MBOT_MIN_MOVE_S: Final = 0.1
MBOT_MAX_PROG_S: Final = 30.0
MBOT_MAX_PROG_STEPS: Final = 20
MBOT_ARM_MIN: Final = 40
MBOT_ARM_MAX: Final = 120
MBOT_ARM_HOME: Final = 90
MBOT_GRIP_MIN: Final = 45
MBOT_GRIP_MAX: Final = 120
MBOT_GRIP_HOME: Final = 90
MBOT_OBSTACLE_CM: Final = 10
MBOT_WATCHDOG_S: Final = 3.0
# v1.1 closed-loop steps
MBOT_MAX_STEP_CM: Final = 30
MBOT_MAX_TURN_DEG: Final = 180
MBOT_STEP_SPEED_MIN: Final = 5
MBOT_STEP_SPEED_DEFAULT: Final = 30
MBOT_ODOM_MIN_MS: Final = 100
MBOT_ODOM_MAX_MS: Final = 5000
MBOT_MAX_CMD_ID: Final = 9999
# Firmware refuses longer command text (one BLE write at MTU 512).
MBOT_MAX_PROGRAM_CHARS: Final = 440

#: Subtypes of ``stackchan-event`` frames with ``event_type: "mbot"``.
#: The first seven come from the mBot (``sk_evt``); ``connected`` and
#: ``disconnected`` are generated by the firmware for the BLE link.
MBOT_EVENT_SUBTYPES: Final = frozenset(
    {
        "ready",
        "done",
        "obstacle",
        "stopped",
        "locked",
        "unlocked",
        "button",
        "connected",
        "disconnected",
    }
)

_DIRECTIONS: Final = ("forward", "backward", "left", "right")
_ARM_POSITIONS: Final = ("up", "down", "home")
_GRIP_POSITIONS: Final = ("open", "close", "home")

LIMITS_TEXT: Final = (
    f"Safety limits (enforced by the gateway, Stack-chan and the mBot itself): "
    f"speed 0-100% of {MBOT_MAX_RPM} RPM (about 20 cm/s at 100%); each move lasts "
    f"{MBOT_MIN_MOVE_S}-{MBOT_MAX_MOVE_S:g} s; arm {MBOT_ARM_MIN}-{MBOT_ARM_MAX} deg; "
    f"gripper {MBOT_GRIP_MIN}-{MBOT_GRIP_MAX} deg ({MBOT_GRIP_MIN} closed, "
    f"{MBOT_GRIP_MAX} open); one step at most {MBOT_MAX_STEP_CM} cm, one turn at most "
    f"{MBOT_MAX_TURN_DEG} deg; programs at most {MBOT_MAX_PROG_STEPS} steps and "
    f"{MBOT_MAX_PROG_S:g} s. Forward motion auto-stops below {MBOT_OBSTACLE_CM} cm. "
    f"mbot_stop is always available and always accepted. Tools return as soon "
    f"as the mBot accepts a command; completion arrives later as an 'mbot' "
    f"'done' event."
)

_EMPTY_SCHEMA: Final[dict[str, Any]] = {"type": "object", "properties": {}}

