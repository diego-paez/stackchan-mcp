def _step_speed_schema() -> dict[str, Any]:
    return {
        "type": "integer",
        "minimum": MBOT_STEP_SPEED_MIN,
        "maximum": 100,
        "default": MBOT_STEP_SPEED_DEFAULT,
        "description": f"{MBOT_STEP_SPEED_MIN}-100 % of {MBOT_MAX_RPM} RPM. Default 30.",
    }


def _int_in(args: dict[str, Any], key: str, lo: int, hi: int, default: int | None = None) -> int:
    value = args.get(key, default)
    if value is None:
        raise ValueError(f"{key} is required")
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{key} must be an integer {lo}-{hi}")
    if isinstance(value, float):
        if not value.is_integer():
            raise ValueError(f"{key} must be an integer {lo}-{hi}")
        value = int(value)
    if not lo <= value <= hi:
        raise ValueError(f"{key} must be {lo}-{hi} (got {value})")
    return value


def _servo_args(
    args: dict[str, Any], positions: tuple[str, ...], lo: int, hi: int
) -> dict[str, Any]:
    position = args.get("position")
    angle = args.get("angle")
    if position is not None and angle is not None:
        raise ValueError("give either position or angle, not both")
    if angle is not None:
        return {"angle": _int_in(args, "angle", lo, hi)}
    if position not in positions:
        raise ValueError(f"position must be one of {', '.join(positions)} (or give angle {lo}-{hi})")
    return {"position": position}


def map_mbot_call(name: str, arguments: dict[str, Any] | None) -> tuple[str, dict[str, Any]]:
    """Validate a gateway mbot_* call and map it to the firmware tool.

    Raises ``ValueError`` with an LLM-readable message on bad arguments;
    nothing is sent to the device in that case.
    """
    args = dict(arguments or {})
    device_tool = MBOT_DEVICE_TOOLS[name]

    if name in ("mbot_status", "mbot_stop", "mbot_home", "mbot_read_sensors", "mbot_sync"):
        return device_tool, {}

    if name == "mbot_step":
        return device_tool, {
            "distance_cm": _int_in(args, "distance_cm", -MBOT_MAX_STEP_CM, MBOT_MAX_STEP_CM),
            "speed_percent": _int_in(
                args, "speed_percent", MBOT_STEP_SPEED_MIN, 100, default=MBOT_STEP_SPEED_DEFAULT
            ),
        }

    if name == "mbot_turn":
        return device_tool, {
            "degrees": _int_in(args, "degrees", -MBOT_MAX_TURN_DEG, MBOT_MAX_TURN_DEG),
            "speed_percent": _int_in(
                args, "speed_percent", MBOT_STEP_SPEED_MIN, 100, default=MBOT_STEP_SPEED_DEFAULT
            ),
        }

    if name == "mbot_odometry":
        out: dict[str, Any] = {}
        if args.get("done_id") is not None:
            out["done_id"] = _int_in(args, "done_id", 1, MBOT_MAX_CMD_ID)
        if args.get("stream_ms") is not None:
            period = _int_in(args, "stream_ms", 0, MBOT_ODOM_MAX_MS)
            if 0 < period < MBOT_ODOM_MIN_MS:
                raise ValueError(
                    f"stream_ms must be 0 (off) or {MBOT_ODOM_MIN_MS}-{MBOT_ODOM_MAX_MS}"
                )
            out["stream_ms"] = period
        return device_tool, out

    if name == "mbot_move":
        direction = args.get("direction")
        if direction not in _DIRECTIONS:
            raise ValueError(f"direction must be one of {', '.join(_DIRECTIONS)}")
        speed = _int_in(args, "speed_percent", 0, 100, default=40)
        seconds = args.get("seconds", 1.0)
        if (
            isinstance(seconds, bool)
            or not isinstance(seconds, (int, float))
            or not math.isfinite(seconds)
            or not MBOT_MIN_MOVE_S <= seconds <= MBOT_MAX_MOVE_S
        ):
            raise ValueError(
                f"seconds must be a number {MBOT_MIN_MOVE_S}-{MBOT_MAX_MOVE_S:g} (got {seconds!r})"
            )
        return device_tool, {
            "direction": direction,
            "speed_percent": speed,
            "duration_ms": int(round(seconds * 1000)),
        }

    if name == "mbot_set_led":
        out = {k: _int_in(args, k, 0, 255) for k in ("r", "g", "b")}
        index = args.get("index", "all")
        if index == "all":
            out["index"] = "all"
        else:
            out["index"] = str(_int_in({"index": index}, "index", 1, 5))
        return device_tool, out

    if name == "mbot_arm":
        return device_tool, _servo_args(args, _ARM_POSITIONS, MBOT_ARM_MIN, MBOT_ARM_MAX)

    if name == "mbot_gripper":
        return device_tool, _servo_args(args, _GRIP_POSITIONS, MBOT_GRIP_MIN, MBOT_GRIP_MAX)

    if name == "mbot_run_program":
        steps = args.get("steps")
        if not isinstance(steps, str) or not steps.strip():
            raise ValueError("steps must be a non-empty string")
        if len(steps) > MBOT_MAX_PROGRAM_CHARS:
            raise ValueError(f"steps is too long (max {MBOT_MAX_PROGRAM_CHARS} characters)")
        count = len([s for s in steps.split(";") if s.strip()])
        if count > MBOT_MAX_PROG_STEPS:
            raise ValueError(
                f"program has {count} steps; the limit is {MBOT_MAX_PROG_STEPS}"
            )
        return device_tool, {"steps": steps}

    raise ValueError(f"Unknown mbot tool: {name}")  # pragma: no cover
