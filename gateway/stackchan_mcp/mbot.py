"""Makeblock mBot2 tools, relayed to the firmware's ``self.mbot.*`` tools.

Stack-chan talks to an mBot2 (CyberPi running the Stacky runtime) over a
1-to-1 BLE link; see ``firmware/components/mbot_link/``. The gateway only
exposes friendly MCP tools, checks their arguments against the same safety
limits, and maps them onto the device tools. The firmware validates and
clamps again, and the mBot clamps a third time, so the gateway is the
first of three independent checks, not the only one.

The limits mirror the "Safety limits" table of Stacky protocol v1
(mblock-stacky-bridge ``docs/protocol.md``) and
``firmware/components/mbot_link/mbot_limits.h``.
"""

from __future__ import annotations

import math
from typing import Any, Final

from mcp.types import Tool

